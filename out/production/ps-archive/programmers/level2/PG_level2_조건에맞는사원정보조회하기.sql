SELECT SUM(HR_GRADE.SCORE) AS SCORE,
       HR_EMPLOYEES.EMP_NO,
       HR_EMPLOYEES.EMP_NAME,
       HR_EMPLOYEES.POSITION,
       HR_EMPLOYEES.EMAIL
FROM HR_EMPLOYEES JOIN HR_GRADE ON HR_EMPLOYEES.EMP_NO = HR_GRADE.EMP_NO
WHERE HR_GRADE.YEAR = 2022
GROUP BY HR_EMPLOYEES.EMP_NO
HAVING SUM(HR_GRADE.SCORE) = (SELECT MAX(TOTAL)
                              FROM(SELECT SUM(SCORE) AS TOTAL
                                   FROM HR_GRADE
                                   WHERE YEAR = 2022
                                   GROUP BY EMP_NO) T
                             )